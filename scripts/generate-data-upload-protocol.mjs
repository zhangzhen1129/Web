import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const webDirectory = resolve(scriptDirectory, '..')
const deliveryDirectory = String.fromCodePoint(0x4ea4, 0x4ed8, 0x6750, 0x6599)
const protocolDirectory = String.fromCodePoint(0x670d, 0x52a1, 0x7aef, 0x63a5, 0x53e3, 0x534f, 0x8bae)
const protocolFile = `\u6570\u636e\u4e0a\u4f20.md`
const protocolPath = resolve(webDirectory, '..', deliveryDirectory, protocolDirectory, protocolFile)
const outputPath = resolve(webDirectory, 'src', 'features', 'dataCollection', 'services', 'generated', 'dataUploadProtocol.js')
const phoneLabel = '\u624b\u673a\u53f7'
const responseCodeLabel = '\u54cd\u5e94\u7801'
const fullUploadLabel = '\u662f\u5426\u5168\u91cf\u4e0a\u4f20'

function fail(message) {
  throw new Error(`Data upload protocol generation failed: ${message}`)
}

function rows(markdown) {
  return [...markdown.matchAll(/^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|/gm)]
    .map((match) => ({ field: match[1].trim(), type: match[2].trim(), description: match[3].trim() }))
}

function findPath(protocolRows, label, preferredDepth) {
  const candidates = protocolRows
    .filter((row) => row.description === label)
    .map((row) => row.field.split('.').filter(Boolean))
    .filter((path) => path.length > 0)
  const exact = candidates.find((path) => path.length === preferredDepth)
  if (exact) return exact
  const shortest = candidates.sort((left, right) => left.length - right.length)[0]
  if (!shortest) fail(`missing semantic field ${label}`)
  return shortest
}

const markdown = await readFile(protocolPath, 'utf8')
const urlMatch = markdown.match(/^`(https:\/\/[^`]+)`$/m)
if (!urlMatch) fail('missing HTTPS URL')
const endpoint = new URL(urlMatch[1])
const protocolRows = rows(markdown)
const path = endpoint.pathname
const fullUploadPath = findPath(protocolRows, fullUploadLabel, 1)
const mobilePath = findPath(protocolRows, phoneLabel, 2)
const responseCodePath = findPath(protocolRows, responseCodeLabel, 2)

const content = `// Generated from the server upload protocol by scripts/generate-data-upload-protocol.mjs.\n// Do not edit this file manually.\nexport const dataUploadProtocol = Object.freeze({\n  path: ${JSON.stringify(path)},\n  protocolId: 'data-collection-upload',\n  fullUploadPath: Object.freeze(${JSON.stringify(fullUploadPath)}),\n  mobilePath: Object.freeze(${JSON.stringify(mobilePath)}),\n  responseCodePath: Object.freeze(${JSON.stringify(responseCodePath)}),\n})\n`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, content, 'utf8')
